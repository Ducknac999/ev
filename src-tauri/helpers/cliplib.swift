// Clipboard history for the notch. E.V checks the clipboard's change count twice a second; when
// it changes, the whole clipboard (every type: plain and rich text, images, files) is saved to a
// file, so picking it later puts back exactly what was copied. Passwords and other things apps
// mark as private (the nspasteboard.org markers 1Password, Bitwarden and Keychain use) are never
// read past their types.

private let skipMarkers: Set<String> = [
    "org.nspasteboard.ConcealedType",
    "org.nspasteboard.TransientType",
    "org.nspasteboard.AutoGeneratedType",
    "com.agilebits.onepassword",
    "com.typeit4me.clipping",
    "de.petermaurer.TransientPasteboardType",
    "Pasteboard generator type",
]

/// Whole copies bigger than this aren't kept (a huge image or video copied from an editor).
private let maxBytes = 40 * 1024 * 1024
private let maxPreview = 20_000

private func reply(_ value: [String: Any]) -> UnsafeMutablePointer<CChar>? {
    let data = (try? JSONSerialization.data(withJSONObject: value)) ?? Data("{}".utf8)
    return strdup(String(decoding: data, as: UTF8.self))
}

private func sha(_ data: Data) -> String {
    SHA256.hash(data: data).map { String(format: "%02x", $0) }.joined()
}

/// A small PNG (at most 240 points) of an image, for the notch's list.
private func thumbnail(_ data: Data) -> (String, Int, Int)? {
    guard let source = CGImageSourceCreateWithData(data as CFData, nil) else { return nil }
    let props = CGImageSourceCopyPropertiesAtIndex(source, 0, nil) as? [CFString: Any]
    let width = (props?[kCGImagePropertyPixelWidth] as? Int) ?? 0
    let height = (props?[kCGImagePropertyPixelHeight] as? Int) ?? 0
    let options: [CFString: Any] = [
        kCGImageSourceCreateThumbnailFromImageAlways: true,
        kCGImageSourceThumbnailMaxPixelSize: 240,
        kCGImageSourceCreateThumbnailWithTransform: true,
    ]
    guard let thumb = CGImageSourceCreateThumbnailAtIndex(source, 0, options as CFDictionary) else { return nil }
    let out = NSMutableData()
    guard let dest = CGImageDestinationCreateWithData(out, "public.png" as CFString, 1, nil) else { return nil }
    CGImageDestinationAddImage(dest, thumb, nil)
    guard CGImageDestinationFinalize(dest) else { return nil }
    return ((out as Data).base64EncodedString(), width, height)
}

/// An icon (an app's, or a file's as Finder shows it) as a small PNG, base64.
private func iconPNG(_ path: String, size: CGFloat) -> String? {
    let icon = NSWorkspace.shared.icon(forFile: path)
    let pixels = Int(size * 2)
    guard let rep = NSBitmapImageRep(bitmapDataPlanes: nil, pixelsWide: pixels, pixelsHigh: pixels, bitsPerSample: 8, samplesPerPixel: 4, hasAlpha: true, isPlanar: false, colorSpaceName: .deviceRGB, bytesPerRow: 0, bitsPerPixel: 0) else { return nil }
    rep.size = NSSize(width: size, height: size)
    NSGraphicsContext.saveGraphicsState()
    NSGraphicsContext.current = NSGraphicsContext(bitmapImageRep: rep)
    icon.draw(in: NSRect(x: 0, y: 0, width: size, height: size), from: .zero, operation: .copy, fraction: 1)
    NSGraphicsContext.restoreGraphicsState()
    return rep.representation(using: .png, properties: [:])?.base64EncodedString()
}

private var appIcons: [String: String] = [:]
private let appIconsLock = NSLock()

private func appIcon(_ app: NSRunningApplication?) -> String? {
    guard let app, let bundle = app.bundleIdentifier, let url = app.bundleURL else { return nil }
    appIconsLock.lock()
    defer { appIconsLock.unlock() }
    if let cached = appIcons[bundle] { return cached }
    let png = iconPNG(url.path, size: 32)
    appIcons[bundle] = png
    return png
}

@_cdecl("ev_clip_count")
public func evClipCount() -> Int {
    NSPasteboard.general.changeCount
}

/// Saves what's on the clipboard now into `dir` and describes it. JSON out:
/// {count, skip?} or {count, kind: text|link|image|files, text?, files?, thumb?, width?, height?,
///  hash, bytes, path, app?, bundle?}.
@_cdecl("ev_clip_capture")
public func evClipCapture(_ dir: UnsafePointer<CChar>) -> UnsafeMutablePointer<CChar>? {
    let board = NSPasteboard.general
    let count = board.changeCount
    let types = (board.types ?? []).map(\.rawValue)
    if types.isEmpty { return reply(["count": count, "skip": "empty"]) }
    if let marker = types.first(where: { skipMarkers.contains($0) }) { return reply(["count": count, "skip": marker]) }

    let front = NSWorkspace.shared.frontmostApplication
    var out: [String: Any] = ["count": count]
    if let name = front?.localizedName { out["app"] = name }
    if let bundle = front?.bundleIdentifier { out["bundle"] = bundle }
    if let icon = appIcon(front) { out["appIcon"] = icon }

    // Every item, every type: put back exactly as copied.
    var saved: [[String: Data]] = []
    var total = 0
    for item in board.pasteboardItems ?? [] {
        var pairs: [String: Data] = [:]
        for type in item.types {
            guard let data = item.data(forType: type) else { continue }
            total += data.count
            if total > maxBytes { return reply(["count": count, "skip": "too big"]) }
            pairs[type.rawValue] = data
        }
        if !pairs.isEmpty { saved.append(pairs) }
    }
    if saved.isEmpty { return reply(["count": count, "skip": "empty"]) }

    let files = (board.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL]) ?? []
    let imageType = types.first(where: { ["public.png", "public.tiff", "public.jpeg", "public.heic", "com.compuserve.gif"].contains($0) })
    if !files.isEmpty {
        let paths = files.map(\.path)
        out["kind"] = "files"
        out["files"] = paths
        out["hash"] = sha(Data(paths.joined(separator: "\n").utf8))
        if let first = files.first, paths.count == 1, let image = imageType.flatMap({ board.data(forType: NSPasteboard.PasteboardType($0)) }) ?? (try? Data(contentsOf: first)), image.count < 30_000_000, let (thumb, w, h) = thumbnail(image) {
            out["thumb"] = thumb
            out["width"] = w
            out["height"] = h
        } else if let first = files.first, let icon = iconPNG(first.path, size: 48) {
            out["thumb"] = icon
            out["fileIcon"] = true
        }
    } else if let text = board.string(forType: .string), !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
        let trimmed = text.trimmingCharacters(in: .whitespacesAndNewlines)
        let isLink = !trimmed.contains(where: \.isWhitespace) && (trimmed.hasPrefix("http://") || trimmed.hasPrefix("https://"))
        out["kind"] = isLink ? "link" : "text"
        out["text"] = String(text.prefix(maxPreview))
        out["hash"] = sha(Data(text.utf8))
    } else if let type = imageType, let data = board.data(forType: NSPasteboard.PasteboardType(type)) {
        out["kind"] = "image"
        out["hash"] = sha(data)
        if let (thumb, w, h) = thumbnail(data) {
            out["thumb"] = thumb
            out["width"] = w
            out["height"] = h
        }
    } else {
        // App-private data with nothing to show (a selection inside a design app): not kept.
        return reply(["count": count, "skip": "nothing to show"])
    }

    let folder = URL(fileURLWithPath: String(cString: dir), isDirectory: true)
    try? FileManager.default.createDirectory(at: folder, withIntermediateDirectories: true)
    let path = folder.appendingPathComponent(UUID().uuidString + ".clip")
    guard let blob = try? PropertyListSerialization.data(fromPropertyList: saved, format: .binary, options: 0),
          (try? blob.write(to: path, options: .atomic)) != nil else {
        return reply(["count": count, "skip": "couldn't save"])
    }
    out["path"] = path.path
    out["bytes"] = total
    return reply(out)
}

/// Puts a saved copy back on the clipboard. Returns the clipboard's new change count (so the
/// watcher knows it's E.V's own), or -1.
@_cdecl("ev_clip_restore")
public func evClipRestore(_ path: UnsafePointer<CChar>) -> Int {
    let url = URL(fileURLWithPath: String(cString: path))
    guard let blob = try? Data(contentsOf: url),
          let saved = (try? PropertyListSerialization.propertyList(from: blob, format: nil)) as? [[String: Data]], !saved.isEmpty else { return -1 }
    var count = -1
    let work = {
        let board = NSPasteboard.general
        board.clearContents()
        let items: [NSPasteboardItem] = saved.map { pairs in
            let item = NSPasteboardItem()
            for (type, data) in pairs { item.setData(data, forType: NSPasteboard.PasteboardType(type)) }
            return item
        }
        if board.writeObjects(items) { count = board.changeCount }
    }
    if Thread.isMainThread { work() } else { DispatchQueue.main.sync(execute: work) }
    return count
}

/// ⌘V into the app in front.
@_cdecl("ev_clip_paste_key")
public func evClipPasteKey() -> Bool {
    let source = CGEventSource(stateID: .hidSystemState)
    guard let down = CGEvent(keyboardEventSource: source, virtualKey: 9, keyDown: true),
          let up = CGEvent(keyboardEventSource: source, virtualKey: 9, keyDown: false) else { return false }
    down.flags = .maskCommand
    up.flags = .maskCommand
    down.post(tap: .cghidEventTap)
    up.post(tap: .cghidEventTap)
    return true
}

@_cdecl("ev_clip_free")
public func evClipFree(_ pointer: UnsafeMutablePointer<CChar>?) {
    free(pointer)
}

/// Whether the app in front fills this screen (x, y, width, height in top-left screen points)
/// with a full-screen window: the notch then hides, like the menu bar does. Window sizes and
/// owners need no Screen Recording permission.
@_cdecl("ev_front_fullscreen")
public func evFrontFullscreen(_ x: Double, _ y: Double, _ width: Double, _ height: Double) -> Bool {
    guard let pid = NSWorkspace.shared.frontmostApplication?.processIdentifier,
          let windows = CGWindowListCopyWindowInfo([.optionOnScreenOnly, .excludeDesktopElements], kCGNullWindowID) as? [[String: Any]] else { return false }
    let screen = CGRect(x: x, y: y, width: width, height: height)
    for window in windows {
        guard (window[kCGWindowOwnerPID as String] as? Int32) == pid,
              (window[kCGWindowLayer as String] as? Int) == 0,
              let dict = window[kCGWindowBounds as String] as? NSDictionary,
              let bounds = CGRect(dictionaryRepresentation: dict as CFDictionary) else { continue }
        if abs(bounds.minX - screen.minX) < 1, abs(bounds.minY - screen.minY) < 1, abs(bounds.width - screen.width) < 1, abs(bounds.height - screen.height) < 1 {
            return true
        }
    }
    return false
}

/// Whether E.V's voice is going to speakers (the Mac's own, a display, AirPlay, a speaker) rather
/// than headphones: only over speakers does the mic hear E.V, so only then does it turn itself
/// down while you talk over it.
@_cdecl("ev_output_speakers")
public func evOutputSpeakers() -> Bool {
    var device = AudioDeviceID(0)
    var size = UInt32(MemoryLayout<AudioDeviceID>.size)
    var address = AudioObjectPropertyAddress(mSelector: kAudioHardwarePropertyDefaultOutputDevice, mScope: kAudioObjectPropertyScopeGlobal, mElement: kAudioObjectPropertyElementMain)
    guard AudioObjectGetPropertyData(AudioObjectID(kAudioObjectSystemObject), &address, 0, nil, &size, &device) == noErr else { return true }
    var transport: UInt32 = 0
    size = UInt32(MemoryLayout<UInt32>.size)
    address.mSelector = kAudioDevicePropertyTransportType
    _ = AudioObjectGetPropertyData(device, &address, 0, nil, &size, &transport)
    if transport == kAudioDeviceTransportTypeBuiltIn {
        // The Mac's own output: headphones in the jack ('hdpn') or its speakers ('ispk').
        var source: UInt32 = 0
        size = UInt32(MemoryLayout<UInt32>.size)
        var sourceAddress = AudioObjectPropertyAddress(mSelector: kAudioDevicePropertyDataSource, mScope: kAudioDevicePropertyScopeOutput, mElement: kAudioObjectPropertyElementMain)
        if AudioObjectGetPropertyData(device, &sourceAddress, 0, nil, &size, &source) == noErr { return source != 0x6864_706E }
        return true
    }
    if [kAudioDeviceTransportTypeHDMI, kAudioDeviceTransportTypeDisplayPort, kAudioDeviceTransportTypeAirPlay].contains(transport) { return true }
    var name: Unmanaged<CFString>?
    size = UInt32(MemoryLayout<Unmanaged<CFString>?>.size)
    address.mSelector = kAudioObjectPropertyName
    if AudioObjectGetPropertyData(device, &address, 0, nil, &size, &name) == noErr, let n = name?.takeRetainedValue() as String? {
        let lower = n.lowercased()
        if ["speaker", "display", "tv", "homepod", "soundbar", "monitor"].contains(where: { lower.contains($0) }) { return true }
    }
    return false
}
